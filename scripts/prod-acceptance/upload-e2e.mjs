import { chromium } from "playwright";
const [SESS, ...FILES] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await (await browser.newContext({ storageState: `${SESS}/A.state.json`, viewport: { width: 1440, height: 900 } })).newPage();
await page.goto("https://katalist-web.vercel.app/", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
const btn = page.locator('button[aria-label="Attach file"]:visible').first();
const [chooser] = await Promise.all([page.waitForEvent("filechooser"), btn.click()]);
await chooser.setFiles(FILES);
await page.waitForTimeout(3000);
const chips = await page.locator('[aria-label^="Remove ktest"]:visible').count();
await page.locator('textarea[aria-label="Magic Box"]:visible').fill("KTest file upload end to end");
await page.waitForTimeout(3000);
await page.locator('button[aria-label="Toss Thing"]:visible').first().click();
await page.waitForTimeout(8000);
const toast = (await page.locator("body").innerText()).match(/could not be uploaded[^\n]*/)?.[0] ?? null;
await page.screenshot({ path: new URL("../../output/coey-production-release/screens/52-upload-e2e.png", import.meta.url).pathname });
console.log(JSON.stringify({ chipsBeforeToss: chips, uploadWarning: toast }));
await browser.close();
