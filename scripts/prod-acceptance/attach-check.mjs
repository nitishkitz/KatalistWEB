import { chromium } from "playwright";
const [SESS, FILE] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await (await browser.newContext({ storageState: `${SESS}/A.state.json`, viewport: { width: 1440, height: 900 } })).newPage();
const errs = [];
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 200)); });
await page.goto("https://katalist-web.vercel.app/", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
const btn = page.locator('button[aria-label="Attach file"]:visible');
console.log("visible attach buttons", await btn.count(), "disabled", await btn.first().isDisabled());
const [chooser] = await Promise.all([page.waitForEvent("filechooser", { timeout: 8000 }), btn.first().click()]);
console.log("chooser multiple", chooser.isMultiple());
const el = chooser.element();
await page.waitForTimeout(800);
console.log("input still attached after click", await el.evaluate((n) => n.isConnected));
console.log("chooser input", JSON.stringify(await el.evaluate((n) => ({ accept: n.getAttribute("accept"), cls: n.className, inputs: document.querySelectorAll('input[type=file]').length, idx: [...document.querySelectorAll('input[type=file]')].indexOf(n) }))));
await el.evaluate((n) => n.addEventListener("change", () => { window.__changed = (window.__changed || 0) + 1; }, { capture: true }));
await chooser.setFiles(FILE);
await page.waitForTimeout(4000);
console.log("change events seen", await page.evaluate(() => window.__changed || 0), "files on input", await el.evaluate((n) => n.files?.length));
console.log("textarea", JSON.stringify(await page.locator('textarea[aria-label="Magic Box"]:visible').inputValue()));
console.log("file chip present", await page.getByText("ktest-upload").count());
console.log("errors", JSON.stringify(errs));
await page.screenshot({ path: new URL("../../output/coey-production-release/screens/51-attach.png", import.meta.url).pathname });
await browser.close();
