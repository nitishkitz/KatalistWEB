import { chromium } from "playwright";
const [SESS, FILE] = process.argv.slice(2);
const SHOT = (n) => new URL(`../../output/coey-production-release/screens/70-${n}.png`, import.meta.url).pathname;
const browser = await chromium.launch();
const page = await (await browser.newContext({ storageState: `${SESS}/B.state.json`, viewport: { width: 1440, height: 900 } })).newPage();
let creates = 0;
page.on("request", (r) => { if (r.url().includes("/rpc/coey_create_things")) creates++; });
const box = () => page.locator('textarea[aria-label="Magic Box"]:visible');
const sendLabel = async () => (await page.locator('button[aria-label="Ask Coey"]:visible, button[aria-label="Toss Thing"]:visible').first().getAttribute("aria-label"));
const panel = async () => (await page.locator('[aria-label="Magic Box assistant"]:visible').innerText().catch(() => "")).replace(/\s+/g, " ");
const out = {};
await page.goto("https://katalist-web.vercel.app/", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
out.switchPresent = await page.locator('[aria-label="Magic Box mode"]:visible').count();
out.placeholder = await box().getAttribute("placeholder");
await box().fill("whats pending with avani");
await page.waitForTimeout(3000);
out.labelForQuestion = await sendLabel();
await box().press("Enter");
await page.waitForTimeout(9000);
const a1 = await panel();
out.answer1 = (a1.match(/(No open Things with [^.]*\.|\d+ open Things? with [^.]*\.)( \d+ Things? from [^.]* in your court\.)?/) || [a1.slice(0, 160)])[0];
out.boxClearedAfterAsk = (await box().inputValue()) === "";
await page.screenshot({ path: SHOT("ask-sender") });
await box().fill("and the overdue ones?");
await page.waitForTimeout(3000);
await box().press("Enter");
await page.waitForTimeout(9000);
const a2 = await panel();
out.followUpContinuesPanel = /and the overdue ones\?/.test(a2);
out.answer2 = (a2.match(/(Nothing [^.]*past its date\.|\d+ Things? [^.]* past (its|their) date\.)( \d+ Things? from [^.]*\.)?/) || [a2.slice(0, 160)])[0];
await box().fill("Renew the shop insurance");
await page.waitForTimeout(3000);
out.labelForTask = await sendLabel();
let before = creates;
await box().press("Enter");
await page.waitForTimeout(5000);
out.taskSaved = creates - before;
out.answerClosedAfterToss = (await page.locator('[aria-label="Magic Box assistant"]:visible').count()) === 0;
const [chooser] = await Promise.all([page.waitForEvent("filechooser"), page.locator('button[aria-label="Attach file"]:visible').first().click()]);
await chooser.setFiles(FILE);
await page.waitForTimeout(3000);
out.textAfterAttach = await box().inputValue();
out.chip = await page.locator('[aria-label^="Remove ktest"]:visible').count();
await page.screenshot({ path: SHOT("attach") });
before = creates;
await page.locator('button[aria-label="Toss Thing"]:visible').first().click();
await page.waitForTimeout(7000);
out.attachmentOnlySaved = creates - before;
console.log(JSON.stringify(out, null, 1));
await browser.close();
