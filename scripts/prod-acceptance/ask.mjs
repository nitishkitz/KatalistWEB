import { chromium } from "playwright";
const BASE = "https://katalist-web.vercel.app";
const SESS = process.argv[2];
const OUT = new URL("../../output/coey-production-release/screens/", import.meta.url).pathname;
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: `${SESS}/A.state.json`, viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
let creates = 0;
page.on("request", (r) => { if (r.url().includes("/rpc/coey_create_things")) creates++; });
const box = () => page.locator('textarea[aria-label="Magic Box"]:visible');
const panel = () => page.locator('[aria-label="Magic Box assistant"]:visible, section:has-text("Coey"):visible').first();
await page.goto(`${BASE}/`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.locator('button:has-text("Ask"):visible').first().click();
async function ask(q, shot) {
  await box().fill(q);
  await box().press("Enter");
  await page.waitForTimeout(9000);
  const text = (await page.locator("body").innerText()).replace(/\s+/g, " ");
  if (shot) await page.screenshot({ path: `${OUT}${shot}` });
  return text;
}
const out = [];
let t = await ask("what's pending with Bharat?", "40-ask-person.png");
const openButtons = await page.locator('button:has-text("Open"):visible, a:has-text("Open"):visible').count();
out.push({ q: "what's pending with Bharat?", answer: (t.match(/[0-9]+ open Things? with Bharat KTest\.|No open Things with Bharat KTest\.|Which person do you mean\?|Do you mean[^?]*\?/) || ["(no structured line)"])[0], openButtons });
t = await ask("and Chitra?", null);
out.push({ q: "and Chitra?", answer: (t.match(/I can’t find “Chitra”[^.]*\.|[0-9]+ open Things? with [^.]*\.|No open Things with [^.]*\./) || ["(no structured line)"])[0] });
t = await ask("whos on stale other than me", "41-ask-stale.png");
out.push({ q: "whos on stale other than me", answer: (t.match(/Nothing you sent is past its follow-up time[^.]*\.|[0-9]+ Things? you sent (is|are) past[^.]*\./) || ["(no structured line)"]).at(0) });
t = await ask("show Bharat's overdue Things", null);
out.push({ q: "show Bharat's overdue Things", answer: (t.match(/Nothing with Bharat KTest is past its date\.|[0-9]+ Things? with Bharat KTest (is|are) past (its|their) date\./) || ["(no structured line)"])[0] });
t = await ask("and Avani?", null);
out.push({ q: "and Avani? (follow-up keeps overdue)", answer: (t.match(/Nothing with Avani KTest is past its date\.|[0-9]+ Things? with Avani KTest (is|are) past (its|their) date\.|[0-9]+ open Things? with Avani[^.]*\./) || ["(no structured line)"])[0] });
t = await ask("and Chitra?", "42-ask-chain.png");
out.push({ q: "and Chitra? (unknown keeps context)", answer: (t.match(/I can’t find “Chitra”[^.]*\.|Nothing with [^.]* is past its date\./) || ["(no structured line)"])[0] });
out.push({ thingsCreatedByAsk: creates });
await browser.close();
console.log(JSON.stringify(out, null, 2));
