import { chromium } from "playwright";
const BASE = "https://katalist-web.vercel.app";
const SESS = process.argv[2];
const OUT = new URL("../../output/coey-production-release/screens/", import.meta.url).pathname;
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: `${SESS}/A.state.json`, viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
let creates = 0;
page.on("request", (r) => { if (r.url().includes("/rpc/coey_create_things")) creates++; });
const box = () => page.locator('textarea[aria-label="Magic Box"]:visible');
const vis = (l) => page.locator(`[aria-label="${l}"]:visible`).first();
const read = async (l) => (await vis(l).innerText({ timeout: 1500 }).catch(() => "")).replace(/\s+/g, " ");
const toss = () => page.locator('button[aria-label="Toss Thing"]:visible').first().click();
async function line(text) { await box().fill(""); await box().fill(text); await page.waitForTimeout(2800); return { chips: await read("What Coey understood"), question: await read("Magic Box clarification") }; }
await page.goto(`${BASE}/`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
const out = [];
const header = (await page.locator("header, nav").first().innerText().catch(() => "")).replace(/\s+/g, " ");
out.push({ case: "header uses saved name", ok: /AK/.test(header) || !/KU/.test(header) });
let r = await line("Call Bharat about GST"); out.push({ case: "mention stays with me", ...r });
let b = creates; await toss(); await page.waitForTimeout(3000); out.push({ case: "saved", creates: creates - b });
r = await line("Bharat send the dealer price list by Friday"); out.push({ case: "delegate to Bharat", ...r });
await page.screenshot({ path: `${OUT}20-delegate-bharat.png` });
b = creates; await toss(); await page.waitForTimeout(3000); out.push({ case: "saved", creates: creates - b });
r = await line("Chitra send the invoice"); out.push({ case: "Chitra (not connected, not visible)", ...r });
await page.screenshot({ path: `${OUT}21-unknown-chitra.png` });
b = creates; await toss(); await page.waitForTimeout(2500); out.push({ case: "Toss with unresolved name", creates: creates - b, question: await read("Magic Box clarification") });
await box().fill(""); await page.waitForTimeout(600);
r = await line("Bharath send the GST file"); out.push({ case: "near spelling", ...r });
await page.screenshot({ path: `${OUT}22-near-spelling.png` });
await box().fill(""); await page.waitForTimeout(600);
r = await line("Send the report EOD"); out.push({ case: "EOD", ...r });
await box().fill("");
await browser.close();
console.log(JSON.stringify(out, null, 2));
